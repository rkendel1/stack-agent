// Generated compatibility bridge. The existing runtime remains the implementation.
type Surface = "electron" | "tauri" | "react-native" | "http" | "tool" | "service";
export interface InvokeOptions { readonly method?: string }

/**
 * Why a call to the existing application did not produce a result. `code` is an AppPort error code
 * (standard, or `bridge.*` for failures AppPort has no standard code for); `status` is the upstream
 * HTTP status when there was one. A failure is never returned as a result.
 */
export class BridgeError extends Error {
  readonly code: string;
  readonly status: number | undefined;
  readonly details: Record<string, unknown>;
  readonly retryable: boolean;
  constructor(code: string, message: string, details: Record<string, unknown> = {}, retryable = false) {
    super(message);
    this.name = "BridgeError";
    this.code = code;
    this.status = typeof details.status === "number" ? details.status : undefined;
    this.details = details;
    this.retryable = retryable;
  }
}

const DEFAULT_UPSTREAM: string | undefined = null ?? undefined;
const DEFAULT_TIMEOUT_MS = 10_000;
const MAX_ERROR_BODY = 2_048;

/** The existing application's origin: `APPPORT_UPSTREAM`, else the one discovered at generation. */
function upstream(): URL {
  const configured = (globalThis as any).process?.env?.APPPORT_UPSTREAM ?? DEFAULT_UPSTREAM;
  if (!configured) throw new BridgeError("bridge.UPSTREAM_NOT_CONFIGURED", "Set APPPORT_UPSTREAM to the existing application's origin, for example http://127.0.0.1:3000");
  let url: URL;
  try { url = new URL(configured); } catch { throw new BridgeError("bridge.UPSTREAM_NOT_CONFIGURED", `APPPORT_UPSTREAM is not a URL: ${configured}`); }
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password || url.search || url.hash) throw new BridgeError("bridge.UPSTREAM_NOT_CONFIGURED", "APPPORT_UPSTREAM must be an http(s) origin, optionally with a path prefix, and no credentials, query or fragment");
  return url;
}

function timeoutMs(): number {
  const value = Number((globalThis as any).process?.env?.APPPORT_UPSTREAM_TIMEOUT_MS);
  return Number.isFinite(value) && value > 0 ? value : DEFAULT_TIMEOUT_MS;
}

/** Upstream HTTP status → AppPort error. Upstream 401/403 are reported as the upstream's refusal, not as AppPort authorization. */
function failureCode(status: number): { code: string; retryable: boolean } {
  if (status === 400 || status === 422) return { code: "INVALID_INPUT", retryable: false };
  if (status === 404) return { code: "NOT_FOUND", retryable: false };
  if (status === 409) return { code: "CONFLICT", retryable: false };
  if (status === 413) return { code: "PAYLOAD_TOO_LARGE", retryable: false };
  if (status === 429) return { code: "RATE_LIMITED", retryable: true };
  if (status >= 500) return { code: "bridge.UPSTREAM_FAILED", retryable: [502, 503, 504].includes(status) };
  return { code: "bridge.UPSTREAM_REJECTED", retryable: false };
}

function upstreamMessage(body: unknown, fallback: string): string {
  if (body && typeof body === "object") for (const key of ["error", "message", "detail"]) { const value = (body as Record<string, unknown>)[key]; if (typeof value === "string" && value) return value; }
  return typeof body === "string" && body ? body.slice(0, 200) : fallback;
}

function queryValue(value: unknown): string { return typeof value === "object" ? JSON.stringify(value) : String(value); }

/**
 * One call to one route of the existing application. Path parameters come from the (already validated)
 * request and are URL-encoded; the other fields are the query string for GET, HEAD and DELETE and the
 * JSON body otherwise. The URL can only be the configured origin; redirects are refused, not followed.
 */
export async function invokeHttp(method: string | undefined, target: string, request: unknown): Promise<unknown> {
  // An implementation generated by an earlier AppPort calls invokeExisting without the binding's method, and
  // `appport add` preserves it (it is developer-owned), so regenerating alone does not fix it.
  if (!method) throw new BridgeError("bridge.BINDING_INVALID", `The call for ${target} names no HTTP method. appport/implementation/index.ts predates method-aware bindings: delete it and run \`appport add\` again, or pass { method } (from appport.bridge.json) as invokeExisting's fifth argument`);
  const verb = method.toUpperCase();
  const input: Record<string, unknown> = request && typeof request === "object" && !Array.isArray(request) ? { ...(request as Record<string, unknown>) } : {};
  const origin = upstream();
  const absolute = /^https?:\/\//.test(target);
  const routePath = absolute ? new URL(target).pathname : target;
  const missing: string[] = [];
  const path = routePath.replace(/:([A-Za-z_][A-Za-z0-9_]*)|\{([A-Za-z_][A-Za-z0-9_]*)(?::[^}]*)?\}/g, (_token, colon?: string, brace?: string) => {
    const name = (colon ?? brace)!;
    const value = input[name];
    delete input[name];
    if (value === undefined || value === null || value === "") { missing.push(name); return ""; }
    return encodeURIComponent(String(value));
  });
  if (missing.length) throw new BridgeError("INVALID_INPUT", `Missing path parameter${missing.length > 1 ? "s" : ""} ${missing.join(", ")} for ${verb} ${routePath}`, { missing });
  const prefix = origin.pathname.replace(/\/+$/, "");
  const url = new URL(`${prefix}${path.startsWith("/") ? path : `/${path}`}`, origin.origin);
  if (url.origin !== origin.origin) throw new BridgeError("bridge.BINDING_INVALID", `${verb} ${routePath} would leave ${origin.origin}`);
  const hasBody = !["GET", "HEAD", "DELETE"].includes(verb);
  if (!hasBody) for (const [name, value] of Object.entries(input)) {
    if (value === undefined || value === null) continue;
    if (Array.isArray(value)) for (const item of value) url.searchParams.append(name, queryValue(item));
    else url.searchParams.set(name, queryValue(value));
  }
  let response: Response;
  try {
    response = await fetch(url, {
      method: verb,
      redirect: "manual",
      signal: AbortSignal.timeout(timeoutMs()),
      headers: hasBody ? { accept: "application/json", "content-type": "application/json" } : { accept: "application/json" },
      ...(hasBody ? { body: JSON.stringify(input) } : {})
    });
  } catch (error) {
    const name = (error as { name?: string })?.name;
    if (name === "TimeoutError" || name === "AbortError") throw new BridgeError("TIMEOUT", `${verb} ${url.pathname} did not answer within ${timeoutMs()} ms`, {}, true);
    throw new BridgeError("bridge.UPSTREAM_UNAVAILABLE", `${verb} ${url.pathname} could not reach ${origin.origin}: ${error instanceof Error ? error.message : String(error)}`, {}, true);
  }
  const text = await response.text();
  let body: unknown = text;
  if (text) { try { body = JSON.parse(text); } catch { /* not JSON: kept as text */ } }
  else body = null;
  if (response.status >= 300 && response.status < 400) throw new BridgeError("bridge.REDIRECT_REFUSED", `${verb} ${url.pathname} redirected (HTTP ${response.status}); redirects are not followed`, { status: response.status, location: response.headers.get("location") });
  if (!response.ok) {
    const { code, retryable } = failureCode(response.status);
    throw new BridgeError(code, upstreamMessage(body, `${verb} ${url.pathname} returned HTTP ${response.status}`), { status: response.status, body: typeof text === "string" && text.length > MAX_ERROR_BODY ? text.slice(0, MAX_ERROR_BODY) : body }, retryable);
  }
  return body;
}

export async function invokeExisting(surface: Surface, target: string, source: string, request: unknown, options: InvokeOptions = {}): Promise<unknown> {
  const root = globalThis as any;
  if (surface === "electron") { let invoke = root.electron?.ipcRenderer?.invoke ?? root.window?.electron?.ipcRenderer?.invoke; if (!invoke && root.process?.versions?.electron) { const electron = await import("electron"); invoke = electron.ipcRenderer?.invoke.bind(electron.ipcRenderer); } if (!invoke) throw new Error(`Electron bridge unavailable for ${target}`); return invoke(target, request); }
  if (surface === "tauri") { const invoke = root.__TAURI_INTERNALS__?.invoke ?? root.__TAURI__?.core?.invoke; if (!invoke) throw new Error(`Tauri bridge unavailable for ${target}`); return invoke(target, request); }
  if (surface === "react-native") { const [module, method] = target.split("."); const fn = root.NativeModules?.[module]?.[method]; if (typeof fn !== "function") throw new Error(`Native bridge unavailable for ${target}`); return fn(request); }
  if (surface === "http") return invokeHttp(options.method, target, request);
  if (source) { const load = Function("specifier", "return import(specifier)") as (specifier: string) => Promise<Record<string, unknown>>; const module = await load(new URL(`../../${source}`, import.meta.url).href); const fn = module[target]; if (typeof fn === "function") return (fn as (input: unknown) => unknown)(request); }
  throw new Error(`No existing-runtime adapter for ${surface}:${target}`);
}
