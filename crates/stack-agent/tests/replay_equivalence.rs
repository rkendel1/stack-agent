//! `--context-profile replay` against the request the base revision sent, and `auto` against
//! `replay` from the same start, through the real binary with a scripted OpenAI-compatible stream
//! and a `pax` stand-in. No real model is called.
//!
//! **The fixture.** `fixtures/replay/aa72067-requests.json` is not a recording of a benchmark run:
//! the historical T4 report keeps per-call measurements, not request bodies. It is every request
//! body the base revision `aa72067` (token accounting, before adaptive context) sent for the scripted
//! trajectory below (read, write, read again, two failing test runs, block) with `--stable-ids
//! --no-state`, generated by running this same file at that revision with
//! `REPLAY_FIXTURE_OUT=<path>` (the base has no `--context-profile`; the variable
//! `CHIP_CONTEXT_PROFILE=replay` set here is ignored there). Temporary paths are normalized.

#![cfg(unix)]

#[path = "support/gated.rs"]
mod gated;

use gated::{FAILED, Model, Pax, Reply, command, project};
use serde_json::Value;

const READ: &str = r#"{"decision":"request_capability","capability":"project.read","inputs":{"path":"src/lib.rs"}}"#;
const WRITE: &str = r#"{"decision":"request_capability","capability":"project.write","inputs":{"path":"src/lib.rs","content":"pub fn one() -> u8 { 1 }\npub fn two() -> u8 { 2 }\n"}}"#;
const TEST: &str = r#"{"decision":"request_capability","capability":"pax.test"}"#;
const BLOCK: &str = r#"{"decision":"block","reason":"scripted"}"#;
const GOAL: &str = "Add `two`.";

/// The scripted trajectory under `profile` (`None`: the variable unset), from a fresh project:
/// every request body with temporary paths normalized, and the report.
async fn trajectory(tag: &str, profile: Option<&str>) -> (Vec<String>, Value) {
    let model = Model::start(vec![
        Reply::Stream(READ),
        Reply::Stream(WRITE),
        Reply::Stream(READ),
        Reply::Stream(TEST),
        Reply::Stream(TEST),
        Reply::Stream(BLOCK),
    ])
    .await;
    let pax = Pax::new(tag, FAILED, false);
    let dir = project(tag);
    let mut c = command(&dir, &model.url, &pax);
    c.env_remove("CHIP_CONTEXT_PROFILE");
    if let Some(p) = profile {
        c.env("CHIP_CONTEXT_PROFILE", p);
    }
    c.args(["work", GOAL, "--json", "--no-state", "--stable-ids"]);
    let out = tokio::task::spawn_blocking(move || c.output().unwrap())
        .await
        .unwrap();
    assert_eq!(
        out.status.code(),
        Some(1),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let stdout = String::from_utf8_lossy(&out.stdout).into_owned();
    let report = serde_json::from_str(stdout.lines().last().unwrap_or("null")).unwrap();
    let (d, p) = (dir.display().to_string(), pax.dir.display().to_string());
    let bodies = model
        .bodies()
        .into_iter()
        .map(|b| b.replace(&d, "<PROJECT>").replace(&p, "<PAX>"))
        .collect();
    (bodies, report)
}

fn fixture_path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/replay/aa72067-requests.json")
}

fn messages(body: &str) -> Vec<(String, String)> {
    let v: Value = serde_json::from_str(body).unwrap();
    v["messages"]
        .as_array()
        .unwrap()
        .iter()
        .map(|m| {
            (
                m["role"].as_str().unwrap().to_string(),
                m["content"].as_str().unwrap_or("").to_string(),
            )
        })
        .collect()
}

/// One request as Chip assembled it: the instructions, each observation, and the user message.
/// The OpenAI-compatible adapter joins consecutive system messages with a blank line; an
/// observation's output is quoted, so a rendered observation never contains that separator.
fn parts(body: &str) -> (String, Vec<String>, String) {
    let m = messages(body);
    assert_eq!(
        m.len(),
        2,
        "one joined system message, then the user message: {m:?}"
    );
    assert_eq!((m[0].0.as_str(), m[1].0.as_str()), ("system", "user"));
    let mut split = m[0].1.split("\n\nObservation:\n");
    let instructions = split.next().unwrap().to_string();
    let observations = split.map(|o| format!("Observation:\n{o}")).collect();
    (instructions, observations, m[1].1.clone())
}

/// Everything in the body but the messages: model, stream, output cap, response format, and so on.
fn settings(body: &str) -> Value {
    let mut v: Value = serde_json::from_str(body).unwrap();
    v.as_object_mut().unwrap().remove("messages");
    v
}

#[tokio::test(flavor = "multi_thread")]
async fn replay_sends_the_base_revisions_requests_byte_for_byte() {
    if let Ok(out) = std::env::var("REPLAY_FIXTURE_OUT") {
        // Generation mode (run at the base revision): write the fixture and check nothing else.
        let (bodies, _) = trajectory("replay-equivalence", None).await;
        std::fs::write(out, serde_json::to_string_pretty(&bodies).unwrap()).unwrap();
        return;
    }
    let base: Vec<String> =
        serde_json::from_str(&std::fs::read_to_string(fixture_path()).unwrap()).unwrap();
    // The default (no flag, no variable) and replay asked for explicitly: the same bytes.
    for (tag, profile) in [
        ("replay-default", None),
        ("replay-explicit", Some("replay")),
    ] {
        let (bodies, report) = trajectory(tag, profile).await;
        assert_eq!(report["tuning"]["context_profile"], "replay", "{tag}");
        compare(&bodies, &base);
    }
}

fn compare(bodies: &[String], base: &[String]) {
    assert_eq!(bodies.len(), base.len(), "the same number of requests");
    for (i, (ours, theirs)) in bodies.iter().zip(base).enumerate() {
        // Semantics first, for a readable failure: settings, then message order, roles, content.
        assert_eq!(settings(ours), settings(theirs), "request {i}: settings");
        let (a, b) = (messages(ours), messages(theirs));
        assert_eq!(
            a.iter().map(|m| &m.0).collect::<Vec<_>>(),
            b.iter().map(|m| &m.0).collect::<Vec<_>>(),
            "request {i}: roles in order"
        );
        for (k, (x, y)) in a.iter().zip(&b).enumerate() {
            assert_eq!(x.1, y.1, "request {i}, message {k}: content");
        }
        // And the claim made: byte for byte.
        assert_eq!(ours, theirs, "request {i}: bytes");
    }
}

#[tokio::test(flavor = "multi_thread")]
async fn auto_and_replay_from_the_same_start_differ_only_where_the_profile_says() {
    let (replay, _) = trajectory("equivalence-replay", Some("replay")).await;
    let (auto, report) = trajectory("equivalence-auto", Some("auto")).await;
    assert_eq!(report["tuning"]["context_profile"], "auto");
    // The same trajectory: the scripted model answers by position, and both runs did the same.
    assert_eq!(auto.len(), replay.len());
    let calls = report["token_usage"]["calls"].as_array().unwrap();
    let mut rows = Vec::new();
    for (i, (a, r)) in auto.iter().zip(&replay).enumerate() {
        assert_eq!(
            settings(a),
            settings(r),
            "request {i}: settings are not the profile's"
        );
        let (ia, obs_a, user_a) = parts(a);
        let (ir, obs_r, user_r) = parts(r);
        // The instructions (goal, authorization rules, capabilities, reply contract): identical.
        assert_eq!(ia, ir, "request {i}: instructions");
        // Observations: auto's are replay's, in the same order, less the ones it names condensed.
        let obs_a: Vec<&String> = obs_a.iter().collect();
        let obs_r: Vec<&String> = obs_r.iter().collect();
        let mut it = obs_r.iter();
        for o in &obs_a {
            assert!(
                it.any(|r| r == o),
                "request {i}: an observation replay did not send, or out of order"
            );
        }
        let withheld: Vec<&&String> = obs_r.iter().filter(|r| !obs_a.contains(r)).collect();
        assert_eq!(
            withheld.len() as u64,
            calls[i]["context"]["observations_condensed"]
                .as_u64()
                .unwrap(),
            "request {i}: every observation not sent is counted as condensed"
        );
        for w in &withheld {
            // Named under Condensed by its execution id, with its bytes withheld.
            let id = w
                .lines()
                .find_map(|l| l.strip_prefix("execution_id: "))
                .map(|q| q.trim_matches('"'))
                .unwrap_or_else(|| panic!("request {i}: no execution id in {w}"));
            assert!(
                user_a.contains(&format!("execution {id} (")),
                "request {i}: {id} withheld but not named:\n{user_a}"
            );
        }
        if !withheld.is_empty() {
            assert!(user_a.contains("bytes withheld"), "{user_a}");
        }
        // The telemetry is the request: the profile and reason recorded are the ones sent.
        let ctx = &calls[i]["context"];
        assert!(
            user_a.contains(&format!(
                "context profile: {} ({}).",
                ctx["profile"].as_str().unwrap(),
                ctx["reason"].as_str().unwrap()
            )),
            "request {i}: {ctx} is not what was sent:\n{user_a}"
        );
        assert_eq!(
            obs_a.len() as u64,
            ctx["observations_in_full"].as_u64().unwrap(),
            "request {i}: observations in full"
        );
        // The user message is replay's with lines added, never removed or reordered: the state,
        // the evidence, prior decisions, ruled-out notes, omissions and the next step all stay.
        let mut lines = user_a.lines();
        for line in user_r.lines() {
            assert!(
                lines.any(|l| l == line),
                "request {i}: replay's line `{line}` is missing or out of order in auto's:\n{user_a}"
            );
        }
        rows.push(serde_json::json!({
            "request": i + 1,
            "profile": calls[i]["context"]["profile"],
            "replay_bytes": r.len(),
            "auto_bytes": a.len(),
            "replay_observations": obs_r.len(),
            "auto_observations": obs_a.len(),
            "condensed": withheld.len(),
        }));
    }
    if let Ok(out) = std::env::var("PROFILE_COMPARISON_OUT") {
        std::fs::write(
            out,
            serde_json::to_string_pretty(&serde_json::json!({
                "note": "request body bytes of one scripted trajectory, the same start for both arms; bytes are a proxy, not tokens, and not a saving",
                "requests": rows,
            }))
            .unwrap(),
        )
        .unwrap();
    }
}

#[tokio::test(flavor = "multi_thread")]
async fn auto_is_deterministic_for_the_same_start() {
    let (a, ra) = trajectory("auto-determinism-a", Some("auto")).await;
    let (b, rb) = trajectory("auto-determinism-b", Some("auto")).await;
    assert_eq!(a, b, "the same start, the same requests, byte for byte");
    let profile = |r: &Value| -> Vec<Value> {
        r["token_usage"]["calls"]
            .as_array()
            .unwrap()
            .iter()
            .map(|c| {
                serde_json::json!([
                    c["context"]["profile"],
                    c["context"]["reason"],
                    c["context"]["sections"]
                ])
            })
            .collect()
    };
    assert_eq!(profile(&ra), profile(&rb));
}
