//! AppPort contract digests, reproduced exactly as `@appport/protocol` computes them.
//!
//! `capabilityDigest(manifest, name, version)` is `sha256:` + hex SHA-256 of the canonical JSON of
//! `{name, definition, integration}` (`packages/protocol/src/publication.ts`): the manifest's definition
//! for that version, and its `appport.integration/1` entry or `null`. Canonical JSON is RFC 8785 as
//! `canonicalize` implements it (`packages/protocol/src/digest.ts`): object members sorted by UTF-16 code
//! units, no whitespace, ECMAScript number and string serialization.
//!
//! Checked against vectors generated by AppPort's own code (`tests/fixtures/appport-capability-digest`),
//! not against this file.

use serde_json::Value;
use sha2::{Digest, Sha256};

const INTEGRATION_EXTENSION: &str = "appport.integration/1";

/// `sha256:<64 lowercase hex>`, the form AppPort publishes.
pub fn is_digest(text: &str) -> bool {
    text.strip_prefix("sha256:").is_some_and(|hex| {
        hex.len() == 64 && hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
    })
}

/// `sha256:` + hex SHA-256 of the canonical JSON of `value`.
pub fn digest_of(value: &Value) -> String {
    let hash = Sha256::digest(canonical_json(value).as_bytes());
    let hex: String = hash.iter().map(|b| format!("{b:02x}")).collect();
    format!("sha256:{hex}")
}

/// The digest of one capability version's contract, or `None` when the manifest has no definition
/// for it (AppPort's `capabilityDigest` returns `undefined` then).
pub fn capability_digest(manifest: &Value, name: &str, version: u64) -> Option<String> {
    let entry = manifest["capabilities"]
        .as_array()?
        .iter()
        .find(|c| c["name"].as_str() == Some(name))?;
    let definition = entry["definitions"]
        .as_array()?
        .iter()
        .find(|d| d["version"].as_f64() == Some(version as f64))?;
    let integration = integration_capabilities(manifest)
        .and_then(|caps| caps.get(&format!("{name}@{version}")))
        .cloned()
        .unwrap_or(Value::Null);
    let mut contract = serde_json::Map::new();
    contract.insert("name".into(), Value::String(name.to_string()));
    contract.insert("definition".into(), definition.clone());
    contract.insert("integration".into(), integration);
    Some(digest_of(&Value::Object(contract)))
}

/// `getIntegration(manifest)?.capabilities`: an object with an object `capabilities`, else nothing.
fn integration_capabilities(manifest: &Value) -> Option<&serde_json::Map<String, Value>> {
    manifest["attributes"][INTEGRATION_EXTENSION]
        .as_object()?
        .get("capabilities")?
        .as_object()
}

/// RFC 8785 canonical JSON, matching `@appport/protocol` `canonicalize`.
pub fn canonical_json(value: &Value) -> String {
    let mut out = String::new();
    write_value(value, &mut out);
    out
}

fn write_value(value: &Value, out: &mut String) {
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        // A JSON number is an IEEE 754 double to the reference implementation, whatever its spelling.
        Value::Number(n) => out.push_str(&ecmascript_number(n.as_f64().unwrap_or(f64::NAN))),
        Value::String(s) => write_string(s, out),
        Value::Array(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_value(item, out);
            }
            out.push(']');
        }
        Value::Object(members) => {
            let mut keys: Vec<&String> = members.keys().collect();
            keys.sort_by(|a, b| a.encode_utf16().cmp(b.encode_utf16()));
            out.push('{');
            for (i, key) in keys.into_iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_string(key, out);
                out.push(':');
                write_value(&members[key], out);
            }
            out.push('}');
        }
    }
}

/// `JSON.stringify` for a string: only `"`, `\` and C0 controls are escaped.
fn write_string(text: &str, out: &mut String) {
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

/// ECMAScript `Number::toString(x)` for a finite double (ECMA-262 §6.1.6.1.20), which is what
/// `JSON.stringify` writes. Rust's `{:e}` gives the same shortest round-trip digits.
fn ecmascript_number(x: f64) -> String {
    if x == 0.0 {
        return "0".into(); // also -0
    }
    if !x.is_finite() {
        return "null".into(); // unreachable for parsed JSON; JSON.stringify writes null
    }
    let sign = if x < 0.0 { "-" } else { "" };
    let sci = format!("{:e}", x.abs());
    let (mantissa, exponent) = sci.split_once('e').unwrap_or((&sci, "0"));
    let digits: String = mantissa.chars().filter(|c| *c != '.').collect();
    let k = digits.len() as i32;
    let n = exponent.parse::<i32>().unwrap_or(0) + 1;
    let body = if k <= n && n <= 21 {
        format!("{digits}{}", "0".repeat((n - k) as usize))
    } else if 0 < n && n <= 21 {
        format!("{}.{}", &digits[..n as usize], &digits[n as usize..])
    } else if -6 < n && n <= 0 {
        format!("0.{}{digits}", "0".repeat((-n) as usize))
    } else {
        let e = n - 1;
        let exp = if e < 0 {
            format!("-{}", -e)
        } else {
            format!("+{e}")
        };
        if k == 1 {
            format!("{digits}e{exp}")
        } else {
            format!("{}.{}e{exp}", &digits[..1], &digits[1..])
        }
    };
    format!("{sign}{body}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_follow_ecmascript() {
        for (x, s) in [
            (1.0, "1"),
            (-1.5, "-1.5"),
            (0.1, "0.1"),
            (1e21, "1e+21"),
            (1e20, "100000000000000000000"),
            (1e-7, "1e-7"),
            (1e-6, "0.000001"),
            (123.456, "123.456"),
            (5e-324, "5e-324"),
            (-0.0, "0"),
        ] {
            assert_eq!(ecmascript_number(x), s, "{x}");
        }
    }

    #[test]
    fn a_digest_has_the_published_form() {
        assert!(is_digest(&digest_of(&Value::Null)));
        assert!(!is_digest("sha256:ABC"));
        assert!(!is_digest(&format!("sha256:{}", "A".repeat(64))));
    }
}
