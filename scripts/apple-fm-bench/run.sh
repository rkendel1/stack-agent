#!/bin/sh
# Reproduce the Apple Foundation Models benchmark. On-device only: no hosted provider is named,
# nothing is downloaded, and `fm serve` binds to loopback. Usage: run.sh OUT_DIR [TRIALS]
#
#   1. environment record
#   2. harness layers `basic` and `select` (arms: none, schema) through `fm respond`
#   3. the real `stack-agent --agent-bench`, local-none arm, through `fm serve`
#   4. optional baseline: LM_BASELINE_MODEL=<id> LM_BASELINE_ENDPOINT=<url> (a server already running)
#
# Every command's exit status is written to OUT_DIR/status.txt.
set -u
OUT=${1:?usage: run.sh OUT_DIR [TRIALS]}
TRIALS=${2:-3}
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
HARNESS=$ROOT/scripts/apple-fm-bench
PORT=${FM_PORT:-1976}
mkdir -p "$OUT"
export NO_COLOR=1
status() { echo "$1 exit=$2" >> "$OUT/status.txt"; }

{
  echo "date: $(date -u +%FT%TZ)"; uname -a; sw_vers; uname -m
  echo "repo: $(git -C "$ROOT" rev-parse HEAD)"; echo "fm: $(command -v fm)"
  fm available 2>&1; fm license --status 2>&1
} > "$OUT/environment.txt" 2>&1

(cd "$HARNESS" && cargo build --release --offline 2>&1 | tail -3); status build $?
BIN=$HARNESS/target/release/apple-fm-bench

# Apple-dialect union for the `schema` arm (generated by Apple's own tool, not hand-written).
fm schema object --name chip_reply --anyOf \
  --schema "$(fm schema object --name request_capability --string decision --string capability)" \
  --schema "$(fm schema object --name complete --string decision --string summary)" \
  --schema "$(fm schema object --name escalate --string decision --string reason)" \
  --schema "$(fm schema object --name block --string decision --string reason)" \
  > "$OUT/decision.schema.json"; status schema-gen $?

"$BIN" basic --trials "$TRIALS" > "$OUT/basic.jsonl" 2> "$OUT/basic.stderr"; status basic $?
"$BIN" select --arm none --trials "$TRIALS" > "$OUT/select-none.jsonl" 2> "$OUT/select-none.stderr"; status select-none $?
"$BIN" select --arm schema --schema-file "$OUT/decision.schema.json" --trials "$TRIALS" \
  > "$OUT/select-schema.jsonl" 2> "$OUT/select-schema.stderr"; status select-schema $?

fm serve --host 127.0.0.1 --port "$PORT" > "$OUT/fm-serve.log" 2>&1 &
SERVE=$!
sleep 3
"$ROOT/target/release/stack-agent" --agent-bench --providers local-none --tasks A,B,C,D,E --trials "$TRIALS" \
  --local-model system --local-endpoint "http://127.0.0.1:$PORT/v1/chat/completions" \
  --env-file /dev/null --out "$OUT/agent-bench-apple" > "$OUT/agent-bench-apple.stdout" 2> "$OUT/agent-bench-apple.stderr"
status agent-bench-apple $?
kill "$SERVE" 2>/dev/null

if [ -n "${LM_BASELINE_MODEL:-}" ]; then
  "$ROOT/target/release/stack-agent" --agent-bench --providers local-none --tasks A,B,C,D,E --trials "$TRIALS" \
    --local-model "$LM_BASELINE_MODEL" --local-endpoint "${LM_BASELINE_ENDPOINT:?set LM_BASELINE_ENDPOINT}" \
    --env-file /dev/null --out "$OUT/agent-bench-baseline" > "$OUT/agent-bench-baseline.stdout" 2> "$OUT/agent-bench-baseline.stderr"
  status agent-bench-baseline $?
fi
python3 -I "$HARNESS/summarize.py" "$OUT" > "$OUT/summary.md"; status summarize $?
